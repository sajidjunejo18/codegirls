<!-- wp:paragraph -->
<p>CodeGirls envisions bridging the gender gap and breaking barriers for women in the tech industry by equipping them with essential skills, mentorship, and placement opportunities. Over the past six years, CodeGirls has empowered over hundreds of women to enter the tech world and make impactful contributions.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>This series, "Voices of CodeGirls", highlights the journeys, work, and achievements of CodeGirls alumnae. Each story is a source of inspiration, showcasing the power of resilience and growth. With four years in Software Quality Assurance, Ghulam Sakina chose to keep learning beyond the workplace. Her journey reflects how continuous learning is important for creating new possibilities in a career.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">Introduction</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>My journey in technology started with a degree in Software Engineering and grew into a career in Software Quality Assurance. With around four years of experience in the industry, I've learned that growth in tech comes from staying curious and continuously building new skills.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">Family Background</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>I come from a supportive family based in Karachi that has always encouraged education, growth, and pursuing opportunities with confidence. Their support played an important role in helping me continue my journey in technology.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">Before CodeGirls</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Before joining CodeGirls, I was already working as a Software Quality Assurance Engineer. While gaining industry experience, I realized the importance of strengthening practical skills and staying aligned with evolving technologies.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">My CodeGirls Journey</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>I enrolled in Phase 2 (Automation) to expand my technical capabilities through hands-on learning and practical exposure. During the program, I worked with tools and concepts including Selenium, Postman, JMeter, and Security Testing, which helped broaden my understanding of software quality and automation.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">Journey of Continuous Learning</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>After completing the program, I was able to apply these learnings directly in my professional work. It strengthened my confidence in automation practices, improved my testing approach, and contributed positively to my career growth.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Being in tech means continuously evolving. Practical learning experiences create opportunities to bridge the gap between existing knowledge and changing industry expectations.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">Stereotypes &amp; Consistency</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Like many women in technology, I have seen assumptions around long-term career growth and opportunities. My experience continues to reinforce that skills, consistency, and willingness to learn create impact far beyond stereotypes. For me, consistency comes from having clear goals and focusing on progress. Every new skill learned becomes motivation to continue growing.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">Looking Ahead</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>My goal is to continue advancing in Quality Assurance and Automation, deepen my expertise, and eventually move into leadership roles where I can contribute strategically and support others in their journeys.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>One of the ways I hope to give back is by encouraging and guiding women entering technology: sharing knowledge, supporting growth, and helping others believe in their potential.</p>
