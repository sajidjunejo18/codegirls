<h2 class="gb-text sec-head__title sec-head__title--left">How CodeGirls Came to Be</h2>
<!-- /wp:generateblocks/text -->
<!-- wp:generateblocks/text {"tagName":"p","globalClasses":["story-text__p"]} -->
<p class="gb-text story-text__p">In 2018, the gender and skills gap in Pakistan's technology industry was hard to ignore. Women remained significantly underrepresented in the tech workforce, creating a challenge for companies, communities, and leaders who wanted to see a more diverse industry.</p>
<!-- /wp:generateblocks/text -->
<!-- wp:generateblocks/text {"tagName":"p","globalClasses":["story-text__p"]} -->
<p class="gb-text story-text__p">One of those people was <strong>Shamim Rajani,</strong> COO of Genetech Solutions.</p>
<!-- /wp:generateblocks/text -->
<!-- wp:generateblocks/text {"tagName":"p","globalClasses":["story-text__p"]} -->
<p class="gb-text story-text__p">Around that time, one of Shamim's business client, <strong>Dr. Hasnain Walji,</strong> Executive Director of United Global Initiative, approached her with a simple question:</p>
<!-- /wp:generateblocks/text -->
<!-- wp:generateblocks/text {"tagName":"p","globalClasses":["story-text__p"]} -->
<p class="gb-text story-text__p"><strong>'How can we make 100 more women tech professionals like you?'</strong></p>
<!-- /wp:generateblocks/text -->
<!-- wp:generateblocks/text {"tagName":"p","globalClasses":["story-text__p"]} -->
<p class="gb-text story-text__p">That question could have remained just a conversation. Instead, Shamim decided to do something about it.</p>
<!-- /wp:generateblocks/text -->
<!-- wp:generateblocks/text {"tagName":"p","globalClasses":["story-text__p"]} -->
<p class="gb-text story-text__p">She knew that the technology industry could become more inclusive simply by offering relevant upskilling and support for women while removing all barriers to access. For that, there was a need for allies who understood the landscape, and would be willing to create opportunities to put those skills to work.</p>
<!-- /wp:generateblocks/text -->
<!-- wp:generateblocks/text {"tagName":"p","globalClasses":["story-text__p"]} -->
<p class="gb-text story-text__p">So she reached out to <strong>Faiza Yousuf</strong>, the Founder of WomenInTechPK, and shared the plan to <strong>train 100 girls in one year under a program sponsored by UGI.</strong></p>
<!-- /wp:generateblocks/text -->
<!-- wp:generateblocks/text {"tagName":"p","globalClasses":["story-text__p"]} -->
<p class="gb-text story-text__p">The initial plan was a three-month program focused on building practical technology skills.</p>
<!-- /wp:generateblocks/text -->
<!-- wp:generateblocks/text {"tagName":"p","globalClasses":["story-text__p"]} -->
<p class="gb-text story-text__p">What started with a target of 100 women grew much faster than expected. The first cohort eventually graduated <strong>280 women</strong>, giving CodeGirls its first glimpse of what this model could become.</p>
